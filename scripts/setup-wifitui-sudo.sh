#!/usr/bin/env bash
set -euo pipefail

# wifitui ships in the Nix profile (~/.nix-profile/bin), but sudo resets PATH to
# /usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin, so `sudo wifitui`
# fails with "command not found".
#
# This script:
#   1. installs /usr/local/bin/wifitui, a tiny wrapper that execs the profile
#      binary (works for both `wifitui` and `sudo wifitui`);
#   2. installs a polkit rule letting the `netdev` group drive NetworkManager
#      from any session, including SSH. The default implicit rule only allows
#      the *active* (local console) session, which is why `wifitui connect`
#      over SSH otherwise needs root.
#
# Safe to re-run. Usage:
#   sudo bash scripts/setup-wifitui-sudo.sh
#   sudo bash scripts/setup-wifitui-sudo.sh --no-polkit

WRAPPER=/usr/local/bin/wifitui
POLKIT_RULE=/etc/polkit-1/rules.d/10-networkmanager-wifi.rules
INSTALL_POLKIT=true

for arg in "$@"; do
    case "$arg" in
        --no-polkit) INSTALL_POLKIT=false ;;
        -h|--help)
            sed -n '2,22p' "$0" | sed 's/^# \{0,1\}//'
            exit 0
            ;;
        *)
            echo "Unknown argument: $arg" >&2
            exit 1
            ;;
    esac
done

if [ "$(uname -s)" != "Linux" ]; then
    echo "Linux-only (NetworkManager + polkit)." >&2
    exit 0
fi

if [ "${EUID:-$(id -u)}" -ne 0 ]; then
    echo "Run with sudo." >&2
    exit 1
fi

target_user=${SUDO_USER:-root}
target_home=$(getent passwd "$target_user" | cut -d: -f6)
[ -n "$target_home" ] || target_home="/home/$target_user"

candidates=(
    "$target_home/.nix-profile/bin/wifitui"
    "/nix/var/nix/profiles/default/bin/wifitui"
    "/run/current-system/sw/bin/wifitui"
)
bin=""
for c in "${candidates[@]}"; do
    if [ -x "$c" ]; then
        bin=$c
        break
    fi
done

if [ -z "$bin" ]; then
    cat >&2 <<EOF
ERROR: wifitui not found. Looked in:
$(printf '  %s\n' "${candidates[@]}")
Install it first (home-manager / nix profile), then re-run.
EOF
    exit 1
fi

echo "==> Installing $WRAPPER -> $bin"
cat >"$WRAPPER" <<EOF
#!/bin/sh
# wifitui is provided by the Nix profile, which is not on sudo's secure_path.
# This wrapper makes both \`wifitui\` and \`sudo wifitui\` resolve.
exec "$bin" "\$@"
EOF
chmod 0755 "$WRAPPER"
echo "    ok"

if [ "$INSTALL_POLKIT" = true ]; then
    echo "==> Installing polkit rule $POLKIT_RULE"
    mkdir -p "$(dirname "$POLKIT_RULE")"
    cat >"$POLKIT_RULE" <<'EOF'
// Autogenerated by dotfiles/scripts/setup-wifitui-sudo.sh - safe to delete.
// Allow the netdev group to manage NetworkManager from any session (including
// SSH). The stock implicit rule only covers the active local session, so
// `wifitui connect` over SSH would otherwise require root.
polkit.addRule(function (action, subject) {
    if (action.id.indexOf("org.freedesktop.NetworkManager.") === 0 &&
        subject.isInGroup("netdev")) {
        return polkit.Result.YES;
    }
});
EOF
    chmod 0644 "$POLKIT_RULE"
    if [ -d /run/systemd/system ]; then
        systemctl restart polkit 2>/dev/null || systemctl restart polkitd 2>/dev/null || true
    fi
    echo "    ok"
fi

if id -nG "$target_user" | tr ' ' '\n' | grep -qx netdev; then
    echo "==> $target_user is in the netdev group"
else
    echo "==> Adding $target_user to the netdev group"
    usermod -aG netdev "$target_user"
    echo "    log out and back in (or reboot) for the group change to apply"
fi

echo
echo "Done. Try:"
echo "    wifitui list"
echo "    sudo wifitui list"
